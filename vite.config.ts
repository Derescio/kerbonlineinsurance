function appPlugins() {
  return [
    tanstackStart(),
    // The Vercel preset is picked automatically when building on Vercel
    nitro({
      // On Vercel the preset turns these into edge rewrites (PostHog's documented Vercel proxy),
      // which pass the visitor's IP on: cookieless IDs and GeoIP depend on it. In local builds
      // (vp preview, E2E) Nitro proxies them itself.
      routeRules: Object.fromEntries(
        posthogProxy.map(({ from, to }) => [`${from}/**`, { proxy: `${to}/**` }]),
      ),
      vercel: {
        // London, next to Neon aws-eu-west-2 (plan/engineering.md section 2)
        functions: { regions: ["lhr1"] },
        // Security headers on every response, static files included. `continue` lets the
        // asset cache route still match. The per-request CSP is set in src/start.ts.
        config: {
          version: 3,
          routes: [{ src: "/(.*)", headers: staticSecurityHeaders, continue: true }],
        },
      },
    }),
    viteReact(),
    // Responsive AVIF/WebP/JPEG sizes from `?w=…&format=…&as=picture` imports, built into /assets
    imagetools(),
  ];
}

