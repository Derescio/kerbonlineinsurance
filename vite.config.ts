// The integration tests run the app as kerb_app (the 0010 role); the setup and the deliberate
// tampering use the owner (TEST_DATABASE_URL). The role's password is set by the global setup.
function appRoleUrl(): string {
  const url = new URL(
    process.env.TEST_DATABASE_URL ?? "postgres://postgres:postgres@localhost:5433/kerb_test",
  );
  url.username = "kerb_app";
  url.password = "kerb_app";
  return url.toString();
}

