// The data contract for the Azure + Databricks pipeline (Phase 9; 4.2, decision 17). One entry per
// table: what a row is, its key, the column an incremental copy watermarks on, whether rows change,
// whether the pipeline copies it, and every column with its downstream treatment. Names are as in
// Postgres. data-contract.test.ts fails CI when this and the schema disagree, and
// constraints.int.test.ts checks every copied table has the 0002 record_delete trigger.

/**
 * - `keep`: copied as is (ids, amounts, statuses, dates of events)
 * - `drop`: personal or secret, never leaves Postgres
 * - `hash`: copied as a keyed hash, so rows can be joined but not read
 * - `bucket`: copied coarsened (date of birth → age band; postcodes are copied as the stored
 *   district, so the full postcode is `drop`)
 */
export type Treatment = "keep" | "drop" | "hash" | "bucket";

export interface TableContract {
  /** What one row is */
  grain: string;
  primaryKey: readonly string[];
  /** The incremental copy's watermark: `updated_at` on mutable tables, `created_at` or the id on append-only ones */
  changeColumn: string | null;
  kind: "mutable" | "append-only";
  /** Copied to the lakehouse (and so has the record_delete trigger) */
  copied: boolean;
  columns: Readonly<Record<string, Treatment>>;
}

function keep(...names: string[]): Record<string, Treatment> {
  return Object.fromEntries(names.map((name) => [name, "keep"]));
}

